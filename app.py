from fastapi import FastAPI, Request, Form
from fastapi.responses import HTMLResponse
from fastapi.templating import Jinja2Templates
from pydantic import BaseModel, field_validator , ValidationError
import joblib
import pandas as pd
from src.utils import log_prediction

app = FastAPI(title="Smart Classroom Occupancy App")

# Configure Jinja2 templates
templates = Jinja2Templates(directory="templates")

MODEL_PATH = "models/occupancy_v1.pkl"
model = joblib.load(MODEL_PATH)

class SensorReadings(BaseModel):
    Temperature: float
    Humidity: float
    Light: float
    CO2: float

    @field_validator('Temperature', 'CO2')
    @classmethod
    def validate_sensors(cls, v, info):
        if info.field_name == 'Temperature' and (v < -10 or v > 50):
            raise ValueError('Temp must be between -10 and 50')
        if info.field_name == 'CO2' and v < 300:
            raise ValueError('CO2 must be above 300ppm')
        return v

# --- WEB FRONTEND ROUTES ---

@app.get("/", response_class=HTMLResponse)
async def read_dashboard(request: Request):
    """Serves the main dashboard page."""
    return templates.TemplateResponse(request=request, name="index.html", context={"result": None})

@app.post("/predict_web", response_class=HTMLResponse)
async def predict_from_form(
    request: Request, 
    Temperature: float = Form(...), 
    Humidity: float = Form(...), 
    Light: float = Form(...), 
    CO2: float = Form(...)
):
    try:
        # 1. Attempt to create the data object (this triggers the validators)
        data = SensorReadings(Temperature=Temperature, Humidity=Humidity, Light=Light, CO2=CO2)
        
        # 2. If successful, get the prediction
        result = predict_occupancy(data)
        
        return templates.TemplateResponse(
            request=request, 
            name="index.html", 
            context={"result": result, "error": None} # Pass None for error
        )

    except ValidationError as e:
        # 3. If validation fails, catch the error and extract the message
        # We take the first error message generated by our @field_validator
        error_msg = e.errors()[0]['msg']
        
        return templates.TemplateResponse(
            request=request, 
            name="index.html", 
            context={"result": None, "error": error_msg} # Pass the message to the UI
        )

# --- JSON API ROUTES ---

@app.post("/predict")
@log_prediction
def predict_occupancy(data: SensorReadings):
    input_df = pd.DataFrame([data.model_dump()])
    prediction = int(model.predict(input_df)[0])
    return {
        "occupancy_prediction": prediction,
        "status": "Occupied" if prediction == 1 else "Empty",
        "confidence": "High"
    }